// Copies ABIs from the Foundry build and the testnet deployment into lib/generated.ts.
// Run after `forge build` / `forge script Deploy`: pnpm sync
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const out = (name) => JSON.parse(readFileSync(join(root, "contracts/out", `${name}.sol`, `${name}.json`), "utf8")).abi;
const names = ["GuardrailVault", "ZhiFactory", "ZhiAttestor", "AllocatorVault", "CreditPool"];
let ts = "// AUTO-GENERATED by scripts/sync-abi.mjs. Do not edit.\n\n";
for (const n of names) ts += `export const ${n[0].toLowerCase() + n.slice(1)}Abi = ${JSON.stringify(out(n))} as const;\n\n`;
const depPath = join(root, "contracts/deployments/injective-testnet.json");
const dep = existsSync(depPath) ? JSON.parse(readFileSync(depPath, "utf8")) : null;
ts += `export const deployment = ${JSON.stringify(dep)} as null | {\n  chainId: number; factory: \`0x\${string}\`; attestor: \`0x\${string}\`; creditPool: \`0x\${string}\`;\n  usdc: \`0x\${string}\`; usdcDenom: string; identityRegistry: \`0x\${string}\`; reputationRegistry: \`0x\${string}\`;\n  vaultImplementation: \`0x\${string}\`; deployer: \`0x\${string}\`; deployedAt: number;\n};\n`;
writeFileSync(join(root, "web/lib/generated.ts"), ts);
console.log(`synced ${names.length} ABIs; deployment: ${dep ? dep.factory : "none yet"}`);
